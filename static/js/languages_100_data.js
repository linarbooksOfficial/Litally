// Helper maps for O(1) lookups
const LITALLY_LANG_MAP = {};
LITALLY_LANGUAGES_100.forEach(l => {
    LITALLY_LANG_MAP[l.code] = l;
});

/**
 * Returns language record by code (defaulting to English)
 */
function getLanguageData(code = 'en') {
    return LITALLY_LANG_MAP[code] || LITALLY_LANG_MAP.en;
}

/**
 * Live Currency Converter: Computes exact localized price in current country's currency.
 * If lang is English ('en'), always shows in USD ($0 / 0 Dollars).
 * If lang is Russian ('ru'), shows in RUB (0 ₽ / 0 рублей).
 * If lang is Kazakh ('kk'), shows in KZT (0 ₸ / 0 теңге).
 * If lang is Chinese ('zh'), shows in CNY (0 ¥ / 0 元).
 * Supports both short symbol format ($0) and long verbal format ($0 / 0 Dollars).
 */
function formatLocalizedTierPrice(usdAmount, langCode = 'en', formatStyle = 'dual') {
    const lang = getLanguageData(langCode);
    const rate = lang.rate || 1.0;
    const symbol = lang.currencySymbol || '$';
    const currName = (langCode === 'ru' && lang.currencyNameRu) ? lang.currencyNameRu : lang.currencyName;

    // Basic tier is always 0
    if (usdAmount === 0) {
        if (formatStyle === 'symbolOnly') { return symbol + '0'; }
        if (formatStyle === 'verbalOnly') { return '0 ' + currName; }
        return symbol + '0 / 0 ' + currName;
    }

    let localAmount = usdAmount * rate;
    let formattedNum;
    const hasCents = (usdAmount % 1 !== 0);

    if (rate >= 1000) {
        localAmount = Math.round(localAmount / 100) * 100;
        formattedNum = localAmount.toLocaleString();
    } else if (rate >= 100) {
        localAmount = Math.round(localAmount / 10) * 10;
        formattedNum = localAmount.toLocaleString();
    } else if (hasCents && rate < 10) {
        // EUR, GBP, USD-like — preserve .99 charm pricing
        formattedNum = localAmount.toFixed(2);
    } else if (hasCents && rate >= 10) {
        // Medium rates (e.g. RUB ~90) — round to whole, but show .99 style
        const whole = Math.round(localAmount);
        // Charm-price: make it end in 9 for authenticity
        formattedNum = (whole - (whole % 10) + 9).toString();
    } else {
        formattedNum = Math.round(localAmount).toLocaleString();
    }

    if (formatStyle === 'symbolOnly' || formatStyle === 'symbol') {
        return symbol + formattedNum;
    }
    if (formatStyle === 'verbalOnly') {
        return formattedNum + ' ' + currName;
    }
    return symbol + formattedNum + ' / ' + formattedNum + ' ' + currName;
}

