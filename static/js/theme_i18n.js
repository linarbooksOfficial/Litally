/**
 * Returns the localized theme title according to the current active language.
 */
function getThemeLocalizedName(theme, lang) {
    if (!theme) return '';
    const idx = (theme.id || 1) - 1;
    if (lang && lang !== 'en' && KAZAKH_THEME_TRANSLATIONS[lang] && KAZAKH_THEME_TRANSLATIONS[lang][idx]) {
        return `${theme.id}. ${KAZAKH_THEME_TRANSLATIONS[lang][idx]}`;
    }
    return theme.name;
}

/**
 * TOGGLE: РЕЖИМ ДЛЯ СЛАБОВИДЯЩИХ (VISUALLY IMPAIRED / HIGH CONTRAST)
 */
function toggleVisionMode() {
    const isImpaired = document.body.classList.toggle('vision-impaired');
    localStorage.setItem('litally_vision_impaired', isImpaired ? 'true' : 'false');
    
    const btn = document.getElementById('labelVisionBtn');
    if (btn) {
        btn.textContent = isImpaired ? '👁️ Обычный режим' : '👁️ Доступность';
    }
    
    if (typeof playChime === 'function') {
        playChime(isImpaired ? 440 : 880);
    }
}

/**
 * TOGGLE: ТЕМА «УТРО / ДЕНЬ» (MORNING EYE-CARE LIGHT PALETTE)
 */
function toggleMorningTheme() {
    const isMorning = document.body.classList.toggle('theme-morning');
    localStorage.setItem('litally_morning_mode', isMorning ? 'true' : 'false');
    
    const btn = document.getElementById('labelMorningBtn');
    if (btn) {
        btn.textContent = isMorning ? '🌙 Вечер' : '🌅 Утро';
    }
    
    if (typeof playChime === 'function') {
        playChime(isMorning ? 660 : 520);
    }
}

// Restore saved preferences on page load
document.addEventListener('DOMContentLoaded', () => {
    if (localStorage.getItem('litally_vision_impaired') === 'true') {
        document.body.classList.add('vision-impaired');
        const btn = document.getElementById('labelVisionBtn');
        if (btn) btn.textContent = '👁️ Обычный режим';
    }
    if (localStorage.getItem('litally_morning_mode') === 'true') {
        document.body.classList.add('theme-morning');
        const btn = document.getElementById('labelMorningBtn');
        if (btn) btn.textContent = '🌙 Вечер';
    }
});
